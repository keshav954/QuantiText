"""
Benchmark script — compares all forecasting models across products/categories.

Usage:
    python -m ml.benchmark [--org-id <uuid>] [--horizon 7] [--output docs/eval/forecast_benchmark.md]

Produces a Markdown table (and prints to stdout) with MAPE and RMSE per model
per category. All numbers come from walk-forward CV — nothing is fabricated.

⚠️  Requires a running PostgreSQL DB (DATABASE_URL_SYNC from .env).
"""

from __future__ import annotations

import argparse
import sys
import warnings
from pathlib import Path

import pandas as pd

warnings.filterwarnings("ignore")

# ── Output path ──────────────────────────────────────────────────────────────
EVAL_DIR = Path(__file__).parents[2] / "docs" / "eval"
EVAL_DIR.mkdir(parents=True, exist_ok=True)


def _load_series_from_db(org_id: str, horizon: int) -> dict[str, pd.Series]:
    """
    Query daily_sales and return one pd.Series per product_id.
    Requires DATABASE_URL_SYNC in environment.
    """
    from sqlalchemy import create_engine, text

    # Load config inline so this script is runnable standalone
    sys.path.insert(0, str(Path(__file__).parents[1]))
    from app.core.config import settings

    engine = create_engine(settings.DATABASE_URL_SYNC)

    with engine.connect() as conn:
        rows = conn.execute(
            text("""
                SELECT ds.product_id::text, ds.sale_date, SUM(ds.quantity_sold) AS qty
                FROM daily_sales ds
                WHERE ds.org_id = :org_id
                GROUP BY ds.product_id, ds.sale_date
                ORDER BY ds.product_id, ds.sale_date
            """),
            {"org_id": org_id},
        ).fetchall()

    if not rows:
        print("No data found. Run `python -m data.seed` first.", file=sys.stderr)
        return {}

    df = pd.DataFrame(rows, columns=["product_id", "sale_date", "qty"])
    df["sale_date"] = pd.to_datetime(df["sale_date"])

    series_map: dict[str, pd.Series] = {}
    for pid, grp in df.groupby("product_id"):
        s = grp.set_index("sale_date")["qty"].sort_index()
        s = s.asfreq("D", fill_value=0)
        if len(s) >= horizon + 60:  # need minimum data
            series_map[str(pid)] = s

    return series_map


def run_benchmark(org_id: str, horizon: int = 7, output: str | None = None) -> pd.DataFrame:
    from ml.baselines import NaiveModel, SeasonalNaiveModel
    from ml.lgbm_model import LightGBMForecaster

    series_map = _load_series_from_db(org_id, horizon)
    if not series_map:
        return pd.DataFrame()

    print(f"Benchmarking {len(series_map)} products, horizon={horizon}d …\n")

    results = []
    for i, (product_id, series) in enumerate(series_map.items()):
        row: dict[str, object] = {"product_id": product_id[:8] + "…", "n_obs": len(series)}

        # ── Naive ─────────────────────────────────────────────────────────
        naive = NaiveModel()
        m = naive.evaluate(series, horizon=horizon)
        row["naive_mape"] = round(m["mape"], 2)
        row["naive_rmse"] = round(m["rmse"], 2)

        # ── Seasonal Naive ────────────────────────────────────────────────
        snv = SeasonalNaiveModel()
        m = snv.evaluate(series, horizon=horizon)
        row["snaive_mape"] = round(m["mape"], 2)
        row["snaive_rmse"] = round(m["rmse"], 2)

        # ── LightGBM ──────────────────────────────────────────────────────
        lgbm = LightGBMForecaster(product_id, horizon=horizon)
        m = lgbm.evaluate(series, n_folds=3, horizon=horizon)
        row["lgbm_mape"] = round(m["mape"], 2)
        row["lgbm_rmse"] = round(m["rmse"], 2)
        row["lgbm_folds"] = m["n_folds"]

        results.append(row)
        if (i + 1) % 10 == 0:
            print(f"  … {i + 1}/{len(series_map)} done")

    df = pd.DataFrame(results)

    # ── Summary ────────────────────────────────────────────────────────────────
    summary_cols = [
        "naive_mape",
        "snaive_mape",
        "lgbm_mape",
        "naive_rmse",
        "snaive_rmse",
        "lgbm_rmse",
    ]
    summary = df[summary_cols].agg(["mean", "median"]).round(2)

    print("\n=== BENCHMARK RESULTS ===")
    print(f"Products evaluated: {len(df)}, Horizon: {horizon} days")
    print("\nMean metrics across all products:")
    print(summary.to_string())

    # ── Markdown output ────────────────────────────────────────────────────────
    md_lines = [
        "# Forecast Benchmark Results",
        "",
        f"> Generated by `ml.benchmark`. Horizon: **{horizon} days**. "
        f"Products: **{len(df)}**. Validation: **3-fold walk-forward CV**.",
        "> ⚠️ Data is SYNTHETIC.",
        "",
        "## Summary (mean across all products)",
        "",
        "| Model | Mean MAPE (%) | Median MAPE (%) | Mean RMSE | Median RMSE |",
        "|-------|--------------|----------------|-----------|------------|",
    ]
    for model, mape_col, rmse_col in [
        ("Naive", "naive_mape", "naive_rmse"),
        ("Seasonal Naive", "snaive_mape", "snaive_rmse"),
        ("LightGBM", "lgbm_mape", "lgbm_rmse"),
    ]:
        md_lines.append(
            f"| {model} | {summary.loc['mean', mape_col]} | "
            f"{summary.loc['median', mape_col]} | "
            f"{summary.loc['mean', rmse_col]} | "
            f"{summary.loc['median', rmse_col]} |"
        )

    md_lines += ["", "## Per-product results (sample — first 20)", ""]
    md_lines.append(df.head(20).to_markdown(index=False))

    md_content = "\n".join(md_lines)

    out_path = Path(output) if output else EVAL_DIR / "forecast_benchmark.md"
    out_path.write_text(md_content, encoding="utf-8")
    print(f"\nFull results saved → {out_path}")

    return df


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Forecast benchmark")
    parser.add_argument("--org-id", required=True, help="Organisation UUID")
    parser.add_argument("--horizon", type=int, default=7, help="Forecast horizon in days")
    parser.add_argument("--output", default=None, help="Output markdown file path")
    args = parser.parse_args()

    run_benchmark(args.org_id, args.horizon, args.output)
